function close(s, i, o, c) { let d = 0; for (let j = i; j < s.length; j++) { if (s[j] === o) d++; else if (s[j] === c && !--d) return j; } return s.length; }
function mathHTML(src) {
  let s = src;
  const out = [];
  let i = 0;
  while (i < s.length) {
    if (s.startsWith("frac{", i)) {
      const a1 = i + 4, a2 = close(s, a1, "{", "}"), b1 = a2 + 1, b2 = close(s, b1, "{", "}");
      out.push(`<span class="fr"><i>${mathHTML(s.slice(a1 + 1, a2))}</i><i>${mathHTML(s.slice(b1 + 1, b2))}</i></span>`); i = b2 + 1; continue;
    }
    if (s.startsWith("binom{", i)) {
      const a1 = i + 5, a2 = close(s, a1, "{", "}"), b1 = a2 + 1, b2 = close(s, b1, "{", "}");
      out.push(`(<span class="fr bn"><i>${mathHTML(s.slice(a1 + 1, a2))}</i><i>${mathHTML(s.slice(b1 + 1, b2))}</i></span>)`); i = b2 + 1; continue;
    }
    if (s.startsWith("sqrt(", i)) { const e = close(s, i + 4, "(", ")"); out.push(`√<span class="sq">${mathHTML(s.slice(i + 5, e))}</span>`); i = e + 1; continue; }
    if (s.startsWith("root(", i)) { const e = close(s, i + 4, "(", ")"), n = s.slice(i + 5, e), e2 = close(s, e + 1, "(", ")"); out.push(`<sup>${mathHTML(n)}</sup>√<span class="sq">${mathHTML(s.slice(e + 2, e2))}</span>`); i = e2 + 1; continue; }
    if (s[i] === "^" || s[i] === "_") {
      const tag = s[i] === "^" ? "sup" : "sub";
      let j = i + 1, inner;
      if (s[j] === "(") { const e = close(s, j, "(", ")"); inner = s.slice(j + 1, e); j = e + 1; }
      else { const m = s.slice(j).match(/^(-?\d+|[a-zA-Z]|[α-ω∞])/); inner = m ? m[0] : ""; j += inner.length; }
      out.push(`<${tag}>${mathHTML(inner)}</${tag}>`); i = j; continue;
    }
    const w = s.slice(i).match(/^(alpha|beta|gamma|sigma|mu|pi|Delta|int|sum|inf)\b/);
    if (w) { out.push({ alpha: "α", beta: "β", gamma: "γ", sigma: "σ", mu: "μ", pi: "π", Delta: "Δ", int: "∫", sum: "Σ", inf: "∞" }[w[1]]); i += w[1].length; continue; }
    const two = s.slice(i, i + 2);
    if (two === "<=") { out.push("≤"); i += 2; continue; }
    if (two === ">=") { out.push("≥"); i += 2; continue; }
    if (two === "!=") { out.push("≠"); i += 2; continue; }
    const ch = s[i];
    if (ch === "*") out.push("·");
    else if (ch === "-") out.push("−");
    else if (/[a-zA-Z]/.test(ch) && !/[a-zA-Z]/.test(s[i - 1] || "") && !/[a-zA-Z]/.test(s[i + 1] || "")) out.push(`<var>${ch}</var>`);
    else out.push(esc(ch));
    i++;
  }
  return out.join("");
}
